/** Mount the shared header. Also renders the live system-status pill. */
export function mountHeader(current) {
  const header = document.querySelector('[data-app-header]');
  if (!header) return;
  // Keyboard users would otherwise tab through eight nav links on every page.
  if (!document.querySelector('.skip-link')) {
    const skip = el('<a class="skip-link" href="#main">Skip to main content</a>');
    document.body.insertBefore(skip, document.body.firstChild);
  }
  header.innerHTML = `
    <div class="brand">
      <div class="brand-mark">AB</div>
      <div>
        <div class="brand-name">Asset &amp; Operations Brain</div>
        <div class="brand-sub">Industrial knowledge substrate</div>
      </div>
    </div>
    <nav class="app-nav" aria-label="Primary">
      ${NAV.map(([href, label]) =>
        `<a href="${href}"${href === current ? ' aria-current="page"' : ''}>${esc(label)}</a>`).join('')}
    </nav>
    <div class="header-status" data-system-status role="status" aria-live="polite"
         aria-label="System status">
      <span class="badge neutral">Checking…</span>
    </div>`;
}

/** Poll /health and reflect the real state in the header pill. */
export async function mountSystemStatus(api) {
  const node = document.querySelector('[data-system-status]');
  if (!node) return;
  const paint = async () => {
    try {
      const health = await api.health();
      const badge = { ok: 'ok', degraded: 'warn', down: 'danger' }[health.status] || 'neutral';
      const down = Object.entries(health.dependencies || {})
        .filter(([, value]) => value.status && value.status !== 'up')
        .map(([name]) => name);
      node.innerHTML = `
        <a href="index.html#system" class="badge ${badge}" style="text-decoration:none"
           title="${esc(down.length ? `Degraded: ${down.join(', ')}` : 'All backing services reachable')}">
          ${esc(health.status)}${down.length ? ` · ${esc(down.join(','))}` : ''}
        </a>`;
    } catch {
      node.innerHTML = '<span class="badge danger">API unreachable</span>';
    }
  };
  await paint();
  setInterval(paint, 15000);
}

/** Delegate clicks on asset chips to the graph explorer. */
export function wireAssetLinks(root = document) {
  const open = (chip) => {
    window.location.href = `graph.html?asset=${encodeURIComponent(chip.dataset.asset)}`;
  };
  root.addEventListener('click', (event) => {
    const chip = event.target.closest('[data-asset]');
    if (chip) open(chip);
  });
  root.addEventListener('keydown', (event) => {
    if (event.key !== 'Enter' && event.key !== ' ') return;
    const chip = event.target.closest?.('[data-asset][role="link"]');
    if (!chip) return;
    event.preventDefault();   // Space would otherwise scroll the page
    open(chip);
  });
}

export function qs(name, fallback = null) {
  return new URLSearchParams(window.location.search).get(name) ?? fallback;
}
