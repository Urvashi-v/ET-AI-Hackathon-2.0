def build_pid(path: Path) -> None:
    """A schematic in vector geometry.

    Not a substitute for a real P&ID -- symbol detection and line tracing are not
    built, and this drawing is not a benchmark for them. Its purpose is to
    exercise the *classifier*: dense vector objects with sparse text is the
    drawing signature, and this file has genuinely thousands of line segments.
    """
    buffer = io.BytesIO()
    c = _canvas(buffer, "P&ID CDU-1 Sheet 3 Crude Charge Pumping", landscape=True)
    w, h = PAGE_H, PAGE_W  # landscape

    c.setLineWidth(0.4)

    # Grid background: what makes a drawing vector-dense.
    c.setStrokeGray(0.88)
    for gx in range(30, int(w) - 20, 12):
        c.line(gx, 40, gx, h - 40)
    for gy in range(40, int(h) - 40, 12):
        c.line(30, gy, w - 20, gy)
    c.setStrokeGray(0)

    def vessel(x, y, label, service):
        c.setLineWidth(1.1)
        c.roundRect(x, y, 80, 110, 12)
        c.setFont("Helvetica-Bold", 8)
        c.drawCentredString(x + 40, y - 12, label)
        c.setFont("Helvetica", 6.5)
        c.drawCentredString(x + 40, y - 21, service)
        c.setLineWidth(0.4)

    def pump(x, y, label, service):
        c.setLineWidth(1.1)
        c.circle(x, y, 17)
        c.line(x - 17, y, x - 30, y)
        c.line(x, y + 17, x, y + 30)
        # Impeller marks
        for angle in range(0, 360, 45):
            import math

            c.line(
                x,
                y,
                x + 14 * math.cos(math.radians(angle)),
                y + 14 * math.sin(math.radians(angle)),
            )
        c.setFont("Helvetica-Bold", 8)
        c.drawCentredString(x, y - 30, label)
        c.setFont("Helvetica", 6.5)
        c.drawCentredString(x, y - 39, service)
        c.setLineWidth(0.4)

    def exchanger(x, y, label, service):
        c.setLineWidth(1.1)
        c.rect(x, y, 100, 60)
        for i in range(1, 6):
            c.line(x, y + i * 10, x + 100, y + i * 10)
        c.setFont("Helvetica-Bold", 8)
        c.drawCentredString(x + 50, y - 12, label)
        c.setFont("Helvetica", 6.5)
        c.drawCentredString(x + 50, y - 21, service)
        c.setLineWidth(0.4)

    def instrument(x, y, tag):
        c.setLineWidth(0.9)
        c.circle(x, y, 13)
        c.line(x - 13, y, x + 13, y)
        c.setFont("Helvetica", 6.5)
        c.drawCentredString(x, y + 3, tag[:3])
        c.drawCentredString(x, y - 8, tag[3:].lstrip("-"))
        c.setLineWidth(0.4)

    def valve(x, y, tag):
        c.setLineWidth(1.0)
        c.line(x - 9, y - 8, x + 9, y + 8)
        c.line(x - 9, y + 8, x + 9, y - 8)
        c.line(x - 9, y - 8, x - 9, y + 8)
        c.line(x + 9, y - 8, x + 9, y + 8)
        c.setFont("Helvetica", 6)
        c.drawCentredString(x, y - 20, tag)
        c.setLineWidth(0.4)

    def pipe(points, label=None):
        c.setLineWidth(1.4)
        for (x1, y1), (x2, y2) in zip(points, points[1:], strict=False):
            c.line(x1, y1, x2, y2)
        if label:
            mx = (points[0][0] + points[-1][0]) / 2
            my = (points[0][1] + points[-1][1]) / 2
            c.setFont("Helvetica", 6)
            c.drawString(mx - 30, my + 5, label)
        c.setLineWidth(0.4)

    vessel(80, 300, "V-102", "SUCTION DRUM")
    pump(280, 250, "P-101A", "CRUDE CHARGE (DUTY)")
    pump(280, 150, "P-101B", "CRUDE CHARGE (STANDBY)")
    exchanger(480, 250, "E-104", "CRUDE PREHEAT")
    vessel(680, 240, "T-101", "CRUDE COLUMN")

    pipe([(160, 340), (220, 340), (220, 250), (250, 250)], '8"-P-1501-A1A')
    pipe([(220, 340), (220, 150), (250, 150)])
    pipe([(280, 280), (280, 330), (440, 330), (440, 280), (480, 280)], '6"-P-1502-A1A')
    pipe([(280, 180), (400, 180), (400, 330)])
    pipe([(580, 280), (640, 280), (640, 300), (680, 300)], '6"-P-1503-A1A')

    valve(220, 250, "HV-1501")
    valve(220, 150, "HV-1502")
    valve(440, 330, "HV-1503")
    instrument(340, 330, "PIC-101")
    instrument(160, 380, "LSHH-305")
    instrument(520, 200, "FT-201")
    instrument(600, 340, "PSV-204")

    # Title block, bottom right - the reliable drawing signal.
    c.setLineWidth(1.0)
    c.rect(w - 300, 45, 270, 90)
    c.line(w - 300, 105, w - 30, 105)
    c.line(w - 300, 75, w - 30, 75)
    c.setFont("Helvetica-Bold", 9)
    c.drawString(w - 293, 113, "PIPING AND INSTRUMENTATION DIAGRAM")
    c.setFont("Helvetica", 7)
    c.drawString(w - 293, 85, "CDU-1  CRUDE CHARGE PUMPING")
    c.drawString(w - 293, 55, "DWG No: PID-CDU1-003      REV: 4      DATE: 2018-11-12")

    c.setFont("Helvetica-Oblique", 6)
    c.setFillGray(0.4)
    c.drawString(30, 30, BANNER)

    c.showPage()
    c.save()
    path.write_bytes(buffer.getvalue())


