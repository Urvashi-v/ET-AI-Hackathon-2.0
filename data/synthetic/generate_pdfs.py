#!/usr/bin/env python3
"""Render the synthetic corpus into real PDF files.

The *content* is the same synthetic corpus described in ``SCHEMA.md`` — not a
real plant, and labelled as such on every page. The *files* are real PDFs, which
is the point: they exercise the actual parsing paths rather than a Markdown
shortcut.

Four artefacts, each targeting a specific path through the pipeline:

``sop_4412_rev3.pdf``
    Text-layer PDF with a ruled table. Exercises pdfplumber word geometry,
    paragraph grouping and table-structure extraction.

``inspection_ut_survey_2025.pdf``
    Text-layer PDF that is mostly a wide numeric table. Exercises the "do not
    flatten a table into prose" path, where the row-column association is the
    only thing that makes the numbers mean anything.

``incident_2019_scan.pdf``
    **Image-only PDF with no text layer.** Rendered to raster and re-embedded,
    with a slight rotation so the page is not perfectly axis-aligned. This is
    the OCR path: pdfplumber will find no text, the pipeline must route it to
    OCR, and with no OCR provider configured it must say so rather than
    silently indexing an empty document.

``pid_cdu1_sheet3.pdf``
    A schematic drawn as vector geometry with tag labels: equipment symbols,
    connecting lines, instrument bubbles and a title block. Sparse text over
    dense vector objects is the drawing signature the classifier keys on.

Deterministic: same seed, byte-identical output apart from the PDF's own
creation timestamp, which is pinned so the file hash is stable and ingestion
stays idempotent across regeneration.

Requires ``reportlab`` (a dev dependency; not needed at run time).
"""

