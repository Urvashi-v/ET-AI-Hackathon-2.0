def _canvas(buffer: io.BytesIO, title: str, landscape: bool = False):
    from reportlab.pdfgen import canvas as pdfcanvas

    size = (PAGE_H, PAGE_W) if landscape else (PAGE_W, PAGE_H)
    c = pdfcanvas.Canvas(buffer, pagesize=size)
    c.setTitle(title)
    c.setAuthor("Unified Asset & Operations Brain - synthetic corpus")
    c.setSubject(BANNER)
    c.setProducer("reportlab")
    # reportlab reads these for /CreationDate and /ModDate.
    c._doc.info.invariant = True  # type: ignore[attr-defined]
    return c


def _banner(c, y: float, width: float) -> None:
    c.setFont("Helvetica-Oblique", 7)
    c.setFillGray(0.35)
    c.drawString(40, y, BANNER)
    c.setFillGray(0)


