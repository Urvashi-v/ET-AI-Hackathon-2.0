def _table(c, x: float, y: float, rows: list[list[str]], widths: list[float]) -> float:
    """Draw a ruled table. The rules matter: pdfplumber finds tables from the
    lines, so an unruled table would be read as prose."""
    row_h = 16.0
    total_w = sum(widths)
    top = y

    for row_index, row in enumerate(rows):
        cursor_x = x
        c.setFont("Helvetica-Bold" if row_index == 0 else "Helvetica", 8.5)
        for col_index, cell in enumerate(row):
            c.drawString(cursor_x + 4, y - row_h + 5, str(cell))
            cursor_x += widths[col_index]
        y -= row_h

    # Horizontal rules
    c.setLineWidth(0.5)
    for i in range(len(rows) + 1):
        line_y = top - i * row_h
        c.line(x, line_y, x + total_w, line_y)
    # Vertical rules
    cursor_x = x
    for width in [0.0, *widths]:
        cursor_x += width
        c.line(cursor_x, top, cursor_x, top - len(rows) * row_h)
    return y - 10


