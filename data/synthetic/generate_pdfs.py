def build_scanned_incident(path: Path) -> None:
    """Render text to a raster image, then embed the image in a PDF.

    The result has no text layer at all, which is what a scanned document really
    is. A slight rotation keeps the page off-axis, as a real scan would be.
    """
    from PIL import Image, ImageDraw, ImageFont
    from reportlab.lib.utils import ImageReader

    # 150 DPI A4 - low enough to be a realistic scan, high enough to OCR.
    width, height = 1240, 1754
    image = Image.new("L", (width, height), color=246)  # slightly grey, like paper
    draw = ImageDraw.Draw(image)

    try:
        font = ImageFont.truetype("DejaVuSans.ttf", 22)
        bold = ImageFont.truetype("DejaVuSans-Bold.ttf", 26)
    except OSError:
        font = ImageFont.load_default(size=22)
        bold = ImageFont.load_default(size=26)

    y = 90
    for line in INCIDENT_LINES:
        if not line:
            y += 18
            continue
        is_heading = line.isupper() and len(line) < 60
        draw.text((90, y), line, fill=25, font=bold if is_heading else font)
        y += 40 if is_heading else 33

    draw.text((90, height - 70), BANNER[:96], fill=110, font=ImageFont.load_default(size=16))

    # A real scan is never perfectly square to the platen.
    image = image.rotate(-0.6, resample=Image.BICUBIC, fillcolor=246, expand=False)

    buffer = io.BytesIO()
    c = _canvas(buffer, "INC-2019-07 Incident Investigation Report (scanned)")
    c.drawImage(ImageReader(image), 0, 0, width=PAGE_W, height=PAGE_H)
    c.showPage()
    c.save()
    path.write_bytes(buffer.getvalue())


