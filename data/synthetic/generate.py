def _tag_for(rng: random.Random, asset: str, *, allow_shorthand: bool = False) -> str:
    if asset == "B":
        if allow_shorthand:
            return rng.choice(SHORTHAND_B)
        return rng.choice(TAG_VARIANTS_B)
    if asset == "A":
        return rng.choice(TAG_VARIANTS_A)
    return asset


def _fmt_date(value: date | None, style: str) -> str:
    if value is None:
        return ""
    return value.strftime("%d/%m/%Y") if style == "dmy" else value.isoformat()


def generate_work_orders(rng: random.Random, out_dir: Path) -> Path:
    path = out_dir / "work_orders_cmms_export.csv"
    rows: list[dict[str, object]] = []

    for fact in WORK_ORDER_FACTS:
        closed = None if fact.omit_close_date else fact.opened + timedelta(days=fact.duration_days)
        # Date-format variance between "source systems": half the export uses the
        # Indian day-first convention, as a real SAP export configured for the
        # local locale would.
        style = "dmy" if rng.random() < 0.5 else "iso"

        code = fact.true_failure_code
        if fact.order_type == "CORRECTIVE" and rng.random() < MISCODED_FRACTION:
            code = "OTHER"  # the dropdown default a tired technician picks

        rows.append(
            {
                "wo_id": fact.wo_id,
                "functional_location": FUNCTIONAL_LOCATION
                if fact.asset in ("A", "B")
                else f"CDU1-{fact.asset}",
                "equipment_tag": _tag_for(rng, fact.asset, allow_shorthand=fact.use_shorthand),
                "order_type": fact.order_type,
                "status": "IN_PROGRESS" if fact.omit_close_date else "CLOSED",
                "priority": fact.priority,
                "short_text": fact.short_text,
                "long_text": fact.long_text,
                "as_found": fact.as_found,
                "as_left": fact.as_left,
                "failure_code": code,
                "opened_on": _fmt_date(fact.opened, style),
                "closed_on": _fmt_date(closed, style),
                "downtime_hrs": "" if fact.downtime_hrs is None else f"{fact.downtime_hrs:.1f}",
                "actual_cost": "" if fact.cost is None else str(fact.cost),
            }
        )

    with path.open("w", encoding="utf-8", newline="") as fh:
        fh.write(f"# {BANNER}\n")
        writer = csv.DictWriter(fh, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)
    return path


def generate_inspections(rng: random.Random, out_dir: Path) -> Path:
    path = out_dir / "inspection_ut_readings.csv"
    rows: list[dict[str, object]] = []
    report_seq = 1

    for equipment, cml_id, start, loss_per_year, minimum in CML_SERIES:
        for survey_index, survey_date in enumerate(SURVEY_DATES):
            years = (survey_date - SURVEY_DATES[0]).days / 365.25
            thickness = round(start - loss_per_year * years, 2)
            remaining = round(thickness - minimum, 2)
            observation = (
                "General wall loss consistent with previous survey."
                if remaining > 1.0
                else "Wall loss approaching retirement limit; reduce survey interval."
            )
            rows.append(
                {
                    "report_no": f"UT-{SURVEY_DATES[survey_index].year}-{report_seq:03d}",
                    "equipment_tag": equipment,
                    "cml_id": cml_id,
                    "ndt_method": "UT",
                    "inspection_date": survey_date.isoformat(),
                    "thickness_mm": f"{thickness:.2f}",
                    "min_thickness": f"{minimum:.2f}",
                    "inspector": rng.choice(INSPECTORS),
                    "observation": observation,
                }
            )
        report_seq += 1

    with path.open("w", encoding="utf-8", newline="") as fh:
        fh.write(f"# {BANNER}\n")
        writer = csv.DictWriter(fh, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)
    return path


INCIDENT_2019 = f"""# Incident Investigation Report INC-2019-07

> {BANNER}

Site: {SITE}   Plant: {PLANT}   System: {SYSTEM}
Equipment involved: P-101B (crude charge pump, standby)
Functional location: {FUNCTIONAL_LOCATION}
Date of event: 2019-03-22
Severity: Minor -- no injury, no release outside bund
Investigation status: CLOSED

## What happened

At 02:10 on 22 March 2019 the standby crude charge pump P-101B was started to take
over from the duty pump for a planned changeover. Within four minutes of starting,
the panel operator observed a rising seal-pot level alarm and process fluid was
seen at the outboard seal drain. The pump was stopped and the duty pump restarted.

## Immediate cause

The outboard mechanical seal failed. On strip-down the seal faces were found
scored, with a witness pattern consistent with running without liquid film.

## Root cause

The startup was carried out with the suction valve throttled. Under this
condition suction pressure at the seal chamber fell below the seal's minimum
required value and the faces ran dry during the run-up. The startup procedure in
force at the time, SOP-4412 revision 2, did not require the operator to confirm
suction pressure before starting the pump. There is no interlock preventing a
start with the suction valve throttled.

## Contributing factors

- Changeover carried out at night with reduced supervision.
- The suction valve position is not indicated at the panel.
- The seal's minimum suction pressure is stated in the OEM manual but not in the
  operating procedure.

## Corrective and preventive actions

| ID | Action | Owner | Due | Status |
|---|---|---|---|---|
| CAPA-41 | Replace outboard mechanical seal | Rotating Equipment | 2019-03-25 | CLOSED |
| CAPA-42 | Brief operators on suction valve position before changeover | Operations | 2019-04-15 | CLOSED |

## Lessons learned

Starting a centrifugal pump against a throttled suction is a dry-running risk that
the procedure does not currently guard against. The same exposure exists on the
sibling pump P-101A, which shares the suction line and the same startup procedure.
"""

