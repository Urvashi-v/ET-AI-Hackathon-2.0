"""Deterministic synthetic corpus generator.

Read ``SCHEMA.md`` next to this file first: it documents the plant model, the
schema of every output, and exactly which defects are injected and why.

Two rules govern this file:

1. **The facts are scripted, not sampled.** The plant, the failure history, the
   procedure steps and the incident narratives are written out explicitly below.
   A generator that samples its facts produces noise with no causal structure,
   and a corpus with no causal structure cannot demonstrate that the system
   found a causal structure.
2. **Only the surface forms are varied**, by a seeded PRNG. That is where the
   deliberate messiness lives -- which of six tag spellings a row uses, whether
   the failure code is the real one or the dropdown default, whether a close-out
   date was ever entered.

Same seed, byte-identical output. That is what keeps ingestion idempotent and the
golden question set valid across regeneration.

Everything written here is SYNTHETIC TEST DATA and says so in its own content.
"""

