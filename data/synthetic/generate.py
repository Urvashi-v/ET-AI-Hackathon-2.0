def write_documents(out_dir: Path) -> list[Path]:
    documents = {
        "incident_2019_seal_failure.md": INCIDENT_2019,
        "incident_2022_seal_failure.md": INCIDENT_2022,
        "sop_4412_crude_charge_pump_startup.md": SOP_4412,
        "moc_2023_07_impeller_trim.md": MOC_2023,
    }
    written: list[Path] = []
    for name, content in documents.items():
        path = out_dir / name
        path.write_text(content, encoding="utf-8")
        written.append(path)
    return written


def write_manifest(out_dir: Path, files: list[Path], seed: int) -> Path:
    entries = []
    for path in sorted(files):
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        entries.append(
            {
                "filename": path.name,
                "sha256": digest,
                "byte_size": path.stat().st_size,
            }
        )
    manifest = {
        "generator": "data/synthetic/generate.py",
        "generator_version": GENERATOR_VERSION,
        "seed": seed,
        "data_class": "synthetic_test_data",
        "warning": BANNER,
        "schema": "See data/synthetic/SCHEMA.md",
        "files": entries,
    }
    path = out_dir / "MANIFEST.json"
    path.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    return path


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", default="data/synthetic/generated", help="output directory")
    parser.add_argument("--seed", type=int, default=DEFAULT_SEED, help="PRNG seed")
    args = parser.parse_args(argv)

    out_dir = Path(args.out)
    out_dir.mkdir(parents=True, exist_ok=True)
    rng = random.Random(args.seed)

    files: list[Path] = [
        generate_work_orders(rng, out_dir),
        generate_inspections(rng, out_dir),
        *write_documents(out_dir),
    ]
    manifest = write_manifest(out_dir, files, args.seed)

    print(f"Generated {len(files)} files in {out_dir} (seed={args.seed})")
    for path in sorted(files) + [manifest]:
        print(f"  {path.name:44} {path.stat().st_size:>8,} bytes")
    print("\nAll output is SYNTHETIC TEST DATA. Ingest with data_class=synthetic_test_data.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
